// `weight` thickens every pixel by this much (in logo pixels) on each side, so the
// one-pixel strokes hold their own next to the bold menu text; 0 draws them as is.
// The logo's own colours are mapped onto the site's palette (GridInkBackdrop.jsx
// PALETTES['mk-original']): reds and oranges -> the site red, greens -> teal, blues
// and purples -> blue, magentas -> pink. Greys take the text colour, dimmed.
const SITE = { red: 'rgb(235, 70, 55)', teal: 'rgb(45, 215, 205)', blue: 'rgb(50, 90, 235)', pink: 'rgb(240, 75, 130)' }
const siteColor = (hex) => {
  const r = parseInt(hex.slice(1, 3), 16) / 255
  const g = parseInt(hex.slice(3, 5), 16) / 255
  const b = parseInt(hex.slice(5, 7), 16) / 255
  const max = Math.max(r, g, b)
  const min = Math.min(r, g, b)
  const d = max - min
  if (d < 0.12) return null // a grey: the text colour, dimmed
  let h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4
  h = ((h * 60) + 360) % 360
  if (h < 45 || h >= 330) return SITE.red // red, orange
  if (h < 190) return SITE.teal // yellow-green, green
  if (h < 275) return SITE.blue // blue, violet
  return SITE.pink // purple, magenta
}
const FILLS = RECTS.map(([, , , , f]) => (f === 0 ? ['currentColor', 1] : siteColor(f) ? [siteColor(f), 1] : ['currentColor', 0.55]))

// `part`: 'full' (letters and sprites), 'letters' (the MK) or 'sprites' (the field
// to the right of the letters, for pairing with MK set in the menu font).
const LETTERS_END = 107 // first logo column past the K (the monogram is 101 px wide, the K's tail a few more)
export default function LogoWide({ className = '', title = 'MK Skitka', weight = 0.25, part = 'full' }) {
  const keep = (x) => (part === 'letters' ? x < LETTERS_END : part === 'sprites' ? x >= LETTERS_END : true)
  const x0 = part === 'sprites' ? LETTERS_END : 0
  const x1 = part === 'letters' ? LETTERS_END : W
  return (
    <svg className={className} viewBox={`${x0} 0 ${x1 - x0} ${H}`} shapeRendering={weight ? 'geometricPrecision' : 'crispEdges'} role={part === 'sprites' ? 'presentation' : 'img'} aria-label={part === 'sprites' ? undefined : title} aria-hidden={part === 'sprites' || undefined}>
      {RECTS.map(([x, y, w, h], i) =>
        keep(x) ? <rect key={i} x={x - weight} y={y - weight} width={w + 2 * weight} height={h + 2 * weight} fill={FILLS[i][0]} fillOpacity={FILLS[i][1] === 1 ? undefined : FILLS[i][1]} /> : null
      )}
    </svg>
  )
}
